"""MQL5 bridge: generate, deploy and drive Expert Advisors on the MT5 terminal.

The web app never needs to install the MQL5 compiler - it asks the Bridge agent
(which sits next to the terminal) to:

1. write ``MQL5\\Experts\\MT5Web_<name>.mq5`` inside the terminal data folder,
2. compile it with ``metaeditor64.exe /compile:... /log:...``,
3. keep a signal file in ``MQL5\\Files\\MT5Web_<name>.txt`` that the Expert
   Advisor re-reads on every tick.

That signal file is how your Python strategy (or you, from the dashboard) drives
an EA running *inside* the terminal - no "Allow WebRequest" whitelist needed.
"""

from __future__ import annotations

import logging
import re
import time
from typing import Any

log = logging.getLogger("mt5web.mql5")

SIGNAL_FILE_PREFIX = "MT5Web_"
MQ5_ROOT_HINT = "MQL5"  # used only to build a readable fallback path


class DeployError(RuntimeError):
    pass


